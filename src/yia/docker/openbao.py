def openbao_status(compose: DockerCompose) -> dict[str, object]:
    unavailable: dict[str, object] = {
        "state": "unavailable", "initialized": None, "sealed": None,
    }
    try:
        result = compose.run(
            [
                "exec", "-T", "openbao", "sh", "-c",
                'bao status -format=json; code=$?; [ "$code" -eq 0 ] || [ "$code" -eq 2 ]',
            ],
            capture_output=True,
            operation="openbao-status",
        )
        payload = json.loads(result.stdout)
    except (YiaError, ValueError, TypeError):
        return unavailable
    if not isinstance(payload, dict):
        return unavailable
    initialized, sealed = payload.get("initialized"), payload.get("sealed")
    if not isinstance(initialized, bool) or not isinstance(sealed, bool):
        return unavailable
    state = "uninitialized" if not initialized else "sealed" if sealed else "ready"
    if state == "ready":
        try:
            compose.run(
                ["exec", "-T", "openbao", "wget", "-q", "-O", "/dev/null", OPENBAO_HEALTH_URL],
                capture_output=True,
                operation="openbao-health",
            )
        except YiaError:
            state = "unavailable"
    return {"state": state, "initialized": initialized, "sealed": sealed}


def _not_ready(status: dict[str, object]) -> YiaError:
    state = status["state"]
    action = (
        "bao operator init puis bao operator unseal"
        if state == "uninitialized"
        else "bao operator unseal" if state == "sealed"
        else "bao status et les logs du service"
    )
    return YiaError(
        ErrorCode.OPENBAO_NOT_READY,
        "OpenBao n'est pas disponible ; une opération manuelle est nécessaire.",
        {
            "service": "openbao", "state": state,
            "suggestion": f"Utiliser make shell SERVICE=openbao, puis {action} ; relancer make update.",
        },
    )


def with_openbao_readiness(
    config: NormalizedConfig,
    compose: DockerCompose,
    operation: Callable[[], None],
) -> None:
    try:
        operation()
    except YiaError as exc:
        if config.services.openbao is not None and exc.code is ErrorCode.DOCKER_UNAVAILABLE:
            status = openbao_status(compose)
            if status["state"] in {"uninitialized", "sealed"}:
                raise _not_ready(status) from exc
            if status["state"] == "ready":
                # Compose may still see the last failed healthcheck immediately
                # after manual unseal. Allow one healthcheck interval, then retry
                # once; unrelated Docker failures must still propagate.
                time.sleep(2)
                operation()
            else:
                raise
        else:
            raise
    if config.services.openbao is not None:
        status = openbao_status(compose)
        if status["state"] != "ready":
            raise _not_ready(status)
